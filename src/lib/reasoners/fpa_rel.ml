(* [is_finite x /\ lo <= i < hi -> term = int2bv n i], for [term = to_bv n mode
   x] and [i = to_int mode x]. Unspecified elsewhere. *)
let to_bv_definition term ~signed n =
  match E.term_view term with
  | { E.xs = [_; _; mode; x]; _ } -> (
    match E.type_info x with
    | Ty.Tfloat (eb, sb) ->
      let lo, hi = bv_range ~signed n in
      let i = E.FP.to_int ~eb ~sb ~mode x in
      let guard =
        E.mk_and (E.FP.is_finite ~eb ~sb x)
          (E.mk_and E.Ints.(~$$lo <= i) E.Ints.(i < ~$$hi) false)
          false
      in
      E.mk_imp guard (E.mk_eq ~iff:false term (E.BV.int2bv n i))
    | _ -> assert false)
  | _ -> assert false

(* Lemmas defining [term]. *)
let definitions term =
  match normal_pred term, conv_kind term with
  | Some p, _ -> "fpa_normal_definition", [normal_definition term p]
  | None, Some (To_bv (signed, n)) ->
    "fpa_to_bv_definition", [to_bv_definition term ~signed n]
  | None, _ -> assert false

(* Sends the lemmas of [defs] to the SAT solver, at each round: Tableaux drops
   some instances with disjunctions, and CDCL drops this state (see
   [satml_frontend.ml]). *)
let instantiate ~do_syntactic_matching:_ _ env _ selector =
  if not (Options.get_smt_lib_fpa ())
  then env, []
  else
    let insts =
      E.Set.fold
        (fun term acc ->
          let origin_name, ffs = definitions term in
          List.fold_left
            (fun acc ff ->
              if selector ff ff
              then
                let gf =
                  { E.ff;
                    origin_name;
                    trigger_depth = 0;
                    gdist = -1;
                    hdist = -1;
                    nb_reductions = 0;
                    age = 0;
                    mf = true;
                    gf = false;
                    lem = None;
                    from_terms = [term];
                    theory_elim = false
                  }
                in
                ([], gf, Ex.empty) :: acc
              else acc)
            acc ffs)
        env.defs []
    in
    env, insts

