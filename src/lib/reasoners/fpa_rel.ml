let pow2 n = Z.shift_left Z.one n

let mk_eq_fact ?(ex = Ex.empty) lhs rhs =
  Literal.LTerm (E.mk_eq ~iff:false lhs rhs), ex, Th_util.Other

let int_literal_fact eb_t sb_t name literal (terms, facts) =
  let lhs = E.mk_term (Sy.name name) [eb_t; sb_t] Ty.Tint in
  E.Set.add lhs terms, mk_eq_fact lhs (E.Ints.of_Z literal) :: facts

let real_literal_fact eb_t sb_t name literal (terms, facts) =
  let lhs = E.mk_term (Sy.name name) [eb_t; sb_t] Ty.Treal in
  E.Set.add lhs terms, mk_eq_fact lhs (E.Reals.of_Q literal) :: facts

let real_literal_fact_z eb_t sb_t name literal =
  real_literal_fact eb_t sb_t name (Q.from_z literal)

let zero_literal_fact eb sb (terms, facts) =
  let ty = Ty.Tfloat (eb, sb) in
  let lhs =
    E.mk_term (Sy.name Names.zeroF) [E.Ints.of_int eb; E.Ints.of_int sb] ty
  in
  ( E.Set.add lhs terms,
    mk_eq_fact lhs (E.float Fp_value.Plus_zero eb sb) :: facts )

let compute_emax_min_exp eb sb =
  let bias = (1 lsl (eb - 1)) - 1 in
  let emax = bias + 1 in
  let min_exp = emax + sb - 3 in
  emax, min_exp

let get_literals env eb sb =
  match Hashtbl.find_opt env.literals_cache (eb, sb) with
  | Some c -> c
  | None ->
    let _, min_exp = compute_emax_min_exp eb sb in
    let max_real_q = Fp_value.max_finite_q eb sb in
    let c =
      { max_real_q;
        max_int_z = Q.to_z (Q.floor max_real_q);
        pow2sb = pow2 sb;
        half_pow2sb = pow2 (sb - 1);
        abs_err_rne_denom = pow2 (min_exp + 1);
        abs_err_denom = pow2 min_exp
      }
    in
    Hashtbl.add env.literals_cache (eb, sb) c;
    c

let type_literal_facts env eb sb =
  let c = get_literals env eb sb in
  let eb_t = E.Ints.of_int eb in
  let sb_t = E.Ints.of_int sb in
  (E.Set.empty, [])
  |> int_literal_fact eb_t sb_t E.FP.Names.pow2sb c.pow2sb
  |> int_literal_fact eb_t sb_t E.FP.Names.max_int c.max_int_z
  |> real_literal_fact eb_t sb_t E.FP.Names.max_real c.max_real_q
  |> real_literal_fact_z eb_t sb_t E.FP.Names.pow2sb_real c.pow2sb
  |> real_literal_fact_z eb_t sb_t E.FP.Names.half_pow2sb_real c.half_pow2sb
  |> real_literal_fact_z eb_t sb_t E.FP.Names.abs_err_rne_denom
       c.abs_err_rne_denom
  |> real_literal_fact_z eb_t sb_t E.FP.Names.abs_err_denom c.abs_err_denom
  |> zero_literal_fact eb sb

let mk_fp_literal_facts eb_t sb_t term ~is_nan ~is_zero ~is_infinite
    ~is_positive ~is_negative =
  let mk_fact name b =
    ( E.mk_term (Sy.name name) [eb_t; sb_t; term] Ty.Tbool,
      if b then E.vrai else E.faux )
  in
  [ mk_fact Names.is_nan is_nan;
    mk_fact Names.is_finite (not (is_nan || is_infinite));
    mk_fact Names.is_zero is_zero;
    mk_fact Names.is_infinite is_infinite;
    mk_fact Names.is_positive is_positive;
    mk_fact Names.is_negative is_negative ]

let fp_literal_facts eb sb term v =
  let eb_t = E.Ints.of_int eb in
  let sb_t = E.Ints.of_int sb in
  match v with
  | Fp_value.NaN ->
    mk_fp_literal_facts eb_t sb_t term ~is_nan:true ~is_zero:false
      ~is_infinite:false ~is_positive:false ~is_negative:false
  | Plus_infinity ->
    mk_fp_literal_facts eb_t sb_t term ~is_nan:false ~is_zero:false
      ~is_infinite:true ~is_positive:true ~is_negative:false
  | Minus_infinity ->
    mk_fp_literal_facts eb_t sb_t term ~is_nan:false ~is_zero:false
      ~is_infinite:true ~is_positive:false ~is_negative:true
  | Plus_zero ->
    mk_fp_literal_facts eb_t sb_t term ~is_nan:false ~is_zero:true
      ~is_infinite:false ~is_positive:true ~is_negative:false
  | Minus_zero ->
    mk_fp_literal_facts eb_t sb_t term ~is_nan:false ~is_zero:true
      ~is_infinite:false ~is_positive:false ~is_negative:true
  | Finite q ->
    let to_real_term =
      E.mk_term (Sy.name Names.to_real) [eb_t; sb_t; term] Ty.Treal
    in
    (to_real_term, E.Reals.of_Q q)
    :: mk_fp_literal_facts eb_t sb_t term ~is_nan:false ~is_zero:false
         ~is_infinite:false
         ~is_positive:(Q.sign q > 0)
         ~is_negative:(Q.sign q < 0)

(* [is_normal] and [is_subnormal] of a literal. *)
let normal_literal_facts eb sb term v =
  let mk_fact name b =
    ( E.mk_term (Sy.name name)
        [E.Ints.of_int eb; E.Ints.of_int sb; term]
        Ty.Tbool,
      if b then E.vrai else E.faux )
  in
  [ mk_fact Names.is_normal (Fp_value.is_normal eb v);
    mk_fact Names.is_subnormal (Fp_value.is_subnormal eb v) ]

let process_pred uf ex a domains =
  match E.lit_view a with
  | E.Pred (t, is_neg) -> (
    let { E.f; xs; _ } = E.term_view t in
    match xs with
    | [_; _; x] when is_fpa_ty (E.type_info x) -> (
      match f with
      | Sy.Name { hs; _ } -> (
        let name = Hstring.view hs in
        match Domain.pred_of_name name with
        | Some pred ->
          let r, ex_r = Uf.find uf x in
          let ex = Ex.union ex ex_r in
          if Options.get_debug_fpa () > 0
          then
            Printer.print_dbg ~module_name:"Fpa_rel"
              ~function_name:"process_pred" "%s(%a) = %b (repr %a)" name E.print
              x (not is_neg) X.print r;
          Domains.new_pred r pred is_neg ex domains
        | None -> domains)
      | _ -> domains)
    | _ -> domains)
  | _ -> domains

let mk_eq_fpval_fact rr fp_val ex =
  let eb, sb =
    match X.type_info rr with Ty.Tfloat (eb, sb) -> eb, sb | _ -> assert false
  in
  let fp_r, _ = X.make (E.float fp_val eb sb) in
  let eq = Shostak.L.(view @@ mk_eq rr fp_r) in
  Literal.LSem eq, ex, Th_util.Other

let flush_domain_facts domains =
  Domains.flush_changed_domains
    (fun acc rr d ->
      match Domain.deduce_fpval_eq d with
      | None -> acc
      | Some (fp_val, ex) ->
        if Options.get_debug_fpa () > 0
        then
          Printer.print_dbg ~module_name:"Fpa_rel"
            ~function_name:"flush_domain_facts" "deduced: %a = %a" X.print rr
            Fp_value.pp fp_val;
        mk_eq_fpval_fact rr fp_val ex :: acc)
    [] domains

(* Registers [term] in [Conv_watch] if it is a conversion application, and
   returns the equalities between representatives deduced on registration. *)
let register_conv uf term ds =
  match conv_kind term with
  | Some kind ->
    let cw = Uf.GlobalDomains.find (module Conv_watch) ds in
    let cw = Conv_watch.register uf term kind cw in
    let eqs, cw = Conv_watch.flush_eqs cw in
    Uf.GlobalDomains.add (module Conv_watch) cw ds, eqs
  | None -> ds, []

let register_aefloat_arg_watch uf term ds =
  match E.term_view term with
  | { E.f = Sy.Op FloatEbSb; xs = [eb; sb; mode; _x]; _ } ->
    let eb, _ = Uf.find uf eb in
    let sb, _ = Uf.find uf sb in
    let mode, ex = Uf.find uf mode in
    let fw = Uf.GlobalDomains.find (module AEFloat_arg_watch) ds in
    let fw = AEFloat_arg_watch.register term eb sb mode ~ex fw in
    Uf.GlobalDomains.add (module AEFloat_arg_watch) fw ds
  | _ -> ds

let normal_pred term =
  match E.term_view term with
  | { E.f = Sy.Name { hs; _ }; xs = [_; _; x]; ty = Ty.Tbool; _ } -> (
    let name = Hstring.view hs in
    match E.term_view x with
    | { E.f = Sy.Float _; _ } -> None
    | { E.ty = Ty.Tfloat (eb, sb); _ }
      when String.equal name Names.is_normal
           || String.equal name Names.is_subnormal ->
      Some (String.equal name Names.is_normal, eb, sb, x)
    | _ -> None)
  | _ -> None

(* [is_normal x <-> is_finite x /\ (to_real x <= -c \/ c <= to_real x)] and
   [is_subnormal x <-> is_finite x /\ not is_zero x /\ -c < to_real x < c]. *)
let normal_definition term (normal, eb, sb, x) =
  let c = Fp_value.min_normal_q eb in
  let r = E.FP.to_real ~eb ~sb x in
  let is_finite = E.FP.is_finite ~eb ~sb x in
  let minus_c = E.Reals.of_Q (Q.minus c) in
  let c = E.Reals.of_Q c in
  let body =
    if normal
    then
      E.mk_and is_finite
        (E.mk_or E.Reals.(r <= minus_c) E.Reals.(c <= r) false)
        false
    else
      E.mk_and is_finite
        (E.mk_and
           (E.neg (E.FP.is_zero ~eb ~sb x))
           (E.mk_and E.Reals.(minus_c < r) E.Reals.(r < c) false)
           false)
        false
  in
  E.mk_iff term body

let add env uf _r term =
  if not (Options.get_smt_lib_fpa ())
  then env, Uf.domains uf, []
  else
    let { E.f; ty; _ } = E.term_view term in
    match ty with
    | Ty.Tfloat (eb, sb) ->
      let env =
        if
          not
            (IntPairSet.mem (eb, sb) env.pending_types
            || Hashtbl.mem env.literals_cache (eb, sb))
        then
          { env with pending_types = IntPairSet.add (eb, sb) env.pending_types }
        else env
      in
      let env =
        match f with
        | Sy.Float v ->
          if Options.get_debug_fpa () > 0
          then
            Printer.print_dbg ~module_name:"Fpa_rel" ~function_name:"add"
              "queueing literal facts for %a" E.print term;
          { env with
            pending_literals =
              fp_literal_facts eb sb term v
              @ normal_literal_facts eb sb term v
              @ env.pending_literals
          }
        | _ -> env
      in
      let ds, eqs = register_conv uf term (Uf.domains uf) in
      env, ds, eqs
    | Ty.Treal ->
      (* ae.float applies ae.round on reals *)
      let ds = register_aefloat_arg_watch uf term (Uf.domains uf) in
      env, ds, []
    | Ty.Tbitv _ ->
      let env =
        match conv_kind term with
        | Some (To_bv _) -> { env with defs = E.Set.add term env.defs }
        | _ -> env
      in
      let ds, eqs = register_conv uf term (Uf.domains uf) in
      env, ds, eqs
    | _ ->
      let env =
        if Option.is_some (normal_pred term)
        then { env with defs = E.Set.add term env.defs }
        else env
      in
      let ds, eqs = register_conv uf term (Uf.domains uf) in
      env, ds, eqs

let mk_aefloat_eq_fact term (eb, sb, mode, ex) =
  match E.term_view term with
  | { E.xs = [_; _; _; x]; _ } ->
    let _, min_exp = compute_emax_min_exp eb sb in
    let repl =
      E.mk_term (Sy.Op Float)
        [E.Ints.of_int sb; E.Ints.of_int min_exp; mode; x]
        Ty.Treal
    in
    repl, mk_eq_fact ~ex term repl
  | _ -> assert false

let assume env uf la =
  if not (Options.get_smt_lib_fpa ())
  then env, Uf.domains uf, { Sig_rel.assume = []; remove = [] }
  else
    let ds = Uf.domains uf in
    let new_terms, prec_facts =
      IntPairSet.fold
        (fun (eb, sb) (terms_acc, facts_acc) ->
          let terms, facts = type_literal_facts env eb sb in
          E.Set.union terms terms_acc, facts @ facts_acc)
        env.pending_types (E.Set.empty, [])
    in
    let eval_facts =
      List.map (fun (lhs, rhs) -> mk_eq_fact lhs rhs) env.pending_literals
    in
    let env =
      { env with
        pending_types = IntPairSet.empty;
        pending_literals = [];
        new_terms = E.Set.union new_terms env.new_terms
      }
    in
    let domains = Uf.GlobalDomains.find (module Domains) ds in
    let domains =
      try
        List.fold_left
          (fun domains (_, root, ex, _) ->
            match root with
            | None -> domains
            | Some a -> process_pred uf ex a domains)
          domains la
      with Domain.Inconsistent ex ->
        raise_notrace (Ex.Inconsistent (ex, Uf.cl_extract uf))
    in
    let changed = domains.Domains.changed in
    let pred_facts, domains = flush_domain_facts domains in
    let ds = Uf.GlobalDomains.add (module Domains) domains ds in
    let conv_watch = Uf.GlobalDomains.find (module Conv_watch) ds in
    let conv_watch = Conv_watch.propagate domains changed conv_watch in
    let conv_eqs, conv_lits, conv_watch = Conv_watch.flush conv_watch in
    let conv_facts =
      List.rev_append
        (List.rev_map
           (fun (eq, ex) -> Literal.LSem eq, ex, Th_util.Other)
           conv_eqs)
        (List.rev_map
           (fun (f, ex) -> Literal.LTerm f, ex, Th_util.Other)
           conv_lits)
    in
    let ds = Uf.GlobalDomains.add (module Conv_watch) conv_watch ds in
    (* The terms of the facts, which can be new, are made visible to
       matching. *)
    let env =
      { env with
        new_terms =
          List.fold_left
            (fun acc (f, _) -> E.Set.union (E.max_terms_of_lit f) acc)
            env.new_terms conv_lits
      }
    in
    let aefloat_arg_watch =
      Uf.GlobalDomains.find (module AEFloat_arg_watch) ds
    in
    let ready, aefloat_arg_watch =
      AEFloat_arg_watch.flush_ready aefloat_arg_watch
    in
    let aefloat_terms, aefloat_facts =
      List.split (List.map (fun (term, p) -> mk_aefloat_eq_fact term p) ready)
    in
    let env =
      { env with
        new_terms =
          List.fold_left
            (fun acc t -> E.Set.add t acc)
            env.new_terms aefloat_terms
      }
    in
    let ds =
      Uf.GlobalDomains.add (module AEFloat_arg_watch) aefloat_arg_watch ds
    in
    ( env,
      ds,
      { Sig_rel.assume =
          prec_facts @ eval_facts @ pred_facts @ aefloat_facts @ conv_facts;
        remove = []
      } )

